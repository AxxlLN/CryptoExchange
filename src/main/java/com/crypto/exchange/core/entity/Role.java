package com.crypto.exchange.core.entity;

/**
 * Перечисление ролей пользователей в системе.
 * Используется для разграничения прав доступа (RBAC).
 */
public enum Role {
    /**
     * Обычный пользователь: торги, пополнение/вывод, просмотр своего кошелька.
     */
    ROLE_USER,

    /**
     * Администратор: управление листингом монет, управление пользователями, просмотр аудита.
     */
    ROLE_ADMIN
}